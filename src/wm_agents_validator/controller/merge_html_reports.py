from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timezone

from wm_agents_validator.models.comparison import ComparisonReport, unique_in_order
from wm_agents_validator.report.html_comparison_renderer import render_json_blob

_OPEN_TAG = '<script id="comparison-data" type="application/json">'
_CLOSE_TAG = "</script>"
_DATA_PLACEHOLDER = "__COMPARISON_DATA_JSON__"


def _find_data_blob_span(html_text: str) -> tuple[int, int]:
    """Returns (start, end) character offsets of the raw JSON blob within the
    `<script id="comparison-data">` tag -- shared by `extract_report_json`
    (returns the blob) and `extract_template` (returns everything else).
    """
    start = html_text.find(_OPEN_TAG)
    if start == -1:
        raise ValueError("No embedded comparison-data script tag found -- is this a compare-traces HTML report?")
    start += len(_OPEN_TAG)
    end = html_text.find(_CLOSE_TAG, start)
    if end == -1:
        raise ValueError("Embedded comparison-data script tag has no closing </script> -- malformed/truncated file?")
    return start, end


def extract_report_json(html_text: str) -> str:
    """Recovers the raw, still-serialized JSON text embedded in a
    `compare-traces`-rendered HTML file -- the renderer embeds
    `report.model_dump_json()` verbatim (only escaping `</script` ->
    `<\\/script` so it can't prematurely close the tag), so this just finds
    that blob and reverses the escaping.

    Returns text, not a parsed/validated object, deliberately -- see
    `merge_html_reports`'s docstring for why merging must not go through
    `ComparisonReport.model_validate_json`.

    Uses plain string search rather than a regex -- these files can be tens
    of MB (one row can carry full drill-down detail, e.g. embedded before/
    after screenshots), and a single `str.find`/slice pass is far cheaper
    than a DOTALL regex over the whole document.
    """
    start, end = _find_data_blob_span(html_text)
    return html_text[start:end].replace("<\\/script", "</script")


def extract_template(html_text: str) -> str:
    """Returns this report's HTML with its data blob replaced back by the
    placeholder token -- i.e. the exact template it was rendered from,
    reusable via `render_json_blob(new_json, template=...)`.

    Why this matters: a report's *own* JS/CSS can render fields the current
    codebase's `_TEMPLATE` has no display code for at all (confirmed in
    practice -- a report carrying `input_screenshot`/`output_screenshot`
    rendered them via real `<img>` tags in its own template, while the
    current `_TEMPLATE` has zero references to either field). Merging must
    reuse an input's own template to keep that rendering working, not just
    preserve the underlying data.
    """
    start, end = _find_data_blob_span(html_text)
    return html_text[:start] + _DATA_PLACEHOLDER + html_text[end:]


def extract_report_from_html(html_text: str) -> ComparisonReport:
    """Convenience typed accessor -- validates the embedded report against
    the *current* `ComparisonReport`/`ComparisonRow` model.

    Not used by `merge_html_reports`: pydantic silently drops any field a
    report carries that the current model doesn't declare (`extra="ignore"`
    is the default, and neither model overrides it), which would silently
    lose data from a report generated by a different version of this
    codebase -- confirmed in practice against real reports carrying
    `input_screenshot`/`output_screenshot` fields no longer on `ComparisonRow`.
    Use this only when you specifically want the current schema's view.
    """
    return ComparisonReport.model_validate_json(extract_report_json(html_text))


@dataclass
class MergedReport:
    html: str
    warnings: list[str] = field(default_factory=list)


def merge_html_reports(html_texts: list[str]) -> MergedReport:
    """Combines several already-rendered `compare-traces` HTML reports (e.g.
    one per model, generated in separate runs) into a single self-contained
    HTML report -- same one-window, sortable/filterable/heatmap view as a
    single `compare-traces` invocation would produce, without re-fetching or
    re-verifying anything.

    Merges at the raw-JSON-dict level, not via the `ComparisonReport` pydantic
    model, so that fields the current model doesn't declare (e.g. an older/
    different report carrying screenshot data) pass through untouched instead
    of being silently dropped -- see `extract_report_from_html`'s docstring.

    Re-renders using the *first* input's own template (see `extract_template`)
    rather than this codebase's current `_TEMPLATE`, so any display code that
    template has (e.g. screenshot rendering) survives the merge -- not just
    the underlying data. If the inputs' templates differ, a warning is
    returned rather than silently picking one.
    """
    if not html_texts:
        raise ValueError("html_texts must be a non-empty list")
    reports = [json.loads(extract_report_json(html)) for html in html_texts]
    templates = [extract_template(html) for html in html_texts]

    warnings: list[str] = []
    base_template = templates[0]
    if any(t != base_template for t in templates[1:]):
        warnings.append(
            "Input reports were rendered by different template/JS versions -- using the "
            "first file's template for the merged output. Display features only present in "
            "another input's template (if any) won't render, even though its underlying "
            "row data is still preserved in the merged output."
        )

    rows = [row for report in reports for row in report.get("rows", [])]
    contract_ids = unique_in_order(report.get("contract_id") for report in reports)
    label = contract_ids[0] if len(contract_ids) == 1 else ", ".join(contract_ids)
    merged = {
        "contract_id": label,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "rows": rows,
    }

    html = render_json_blob(json.dumps(merged), template=base_template)
    return MergedReport(html=html, warnings=warnings)
