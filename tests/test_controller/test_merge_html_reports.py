import json

import pytest

from wm_agents_validator.controller.merge_html_reports import (
    extract_report_from_html,
    extract_report_json,
    extract_template,
    merge_html_reports,
)
from wm_agents_validator.models.comparison import ComparisonReport, ComparisonRow, PluginScore
from wm_agents_validator.report.html_comparison_renderer import HtmlComparisonRenderer, render_json_blob


def _report_html(contract_id: str, trace_id: str, model_name: str, contract_name: str | None = None) -> str:
    report = ComparisonReport(
        contract_id=contract_id,
        rows=[
            ComparisonRow(
                trace_id=trace_id,
                model_name=model_name,
                contract_name=contract_name,
                overall_score=1.0,
                passed=True,
                plugin_scores=[PluginScore(plugin="skills_loaded", passed=True, score=1.0)],
            )
        ],
    )
    return HtmlComparisonRenderer().render(report)


def test_extract_report_from_html_round_trips():
    html = _report_html("binding@1.0.0", "trace-claude", "claude")

    report = extract_report_from_html(html)

    assert report.contract_id == "binding@1.0.0"
    assert len(report.rows) == 1
    assert report.rows[0].trace_id == "trace-claude"
    assert report.rows[0].model_name == "claude"


def test_extract_report_from_html_rejects_non_report_html():
    with pytest.raises(ValueError):
        extract_report_from_html("<html><body>not a report</body></html>")


def test_merge_html_reports_combines_rows_from_both_files():
    claude_html = _report_html("binding@1.0.0", "trace-claude", "claude")
    grok_html = _report_html("binding@1.0.0", "trace-grok", "grok")

    result = merge_html_reports([claude_html, grok_html])
    merged_report = extract_report_from_html(result.html)

    assert {row.trace_id for row in merged_report.rows} == {"trace-claude", "trace-grok"}
    assert set(merged_report.model_names) == {"claude", "grok"}
    assert "<!DOCTYPE html>" in result.html
    assert result.warnings == []  # both inputs share the same template


def test_merge_html_reports_rejects_empty_list():
    with pytest.raises(ValueError):
        merge_html_reports([])


def test_merge_html_reports_preserves_fields_unknown_to_the_current_model():
    # Regression: a report generated by a since-changed version of this
    # codebase can carry row fields (e.g. input_screenshot/output_screenshot,
    # confirmed present in real reports) that the *current* ComparisonRow
    # doesn't declare. Merging must not silently drop them -- going through
    # ComparisonReport.model_validate_json would (pydantic's default
    # extra="ignore"), so merge_html_reports works at the raw-JSON level.
    base_html = _report_html("screenshot_to_code@1.0.0", "trace-1", "claude")
    raw_json = json.loads(extract_report_json(base_html))
    raw_json["rows"][0]["input_screenshot"] = "base64-data-not-on-current-model"
    html_with_extra_field = render_json_blob(json.dumps(raw_json))

    result = merge_html_reports([html_with_extra_field])
    merged_raw = json.loads(extract_report_json(result.html))

    assert merged_raw["rows"][0]["input_screenshot"] == "base64-data-not-on-current-model"


def test_merge_html_reports_reuses_first_inputs_template_for_display_code_not_in_current_template():
    # Regression: a report can carry JS/CSS (e.g. real <img> tags rendering
    # input_screenshot/output_screenshot) that the *current* codebase's
    # `_TEMPLATE` has no equivalent for at all. The merged output must reuse
    # an input's own template, not the current codebase's, or that display
    # code -- not just the data -- would be silently lost.
    base_html = _report_html("screenshot_to_code@1.0.0", "trace-1", "claude")
    templated_html = base_html.replace(
        "</body>", '<div id="screenshot-marker-not-in-current-template"></div></body>'
    )

    result = merge_html_reports([templated_html])

    assert 'id="screenshot-marker-not-in-current-template"' in result.html


def test_merge_html_reports_warns_when_input_templates_differ():
    base_html = _report_html("screenshot_to_code@1.0.0", "trace-1", "claude")
    different_template_html = base_html.replace("</body>", '<div id="other-template-marker"></div></body>')

    result = merge_html_reports([base_html, different_template_html])

    assert len(result.warnings) == 1
    assert "different template" in result.warnings[0]


def test_merge_html_reports_preserves_contract_name_and_its_filter_ui():
    login_html = _report_html("pages@1.0.0", "trace-1", "claude", contract_name="Login")
    dashboard_html = _report_html("pages@1.0.0", "trace-2", "claude", contract_name="Dashboard")

    result = merge_html_reports([login_html, dashboard_html])
    merged_report = extract_report_from_html(result.html)

    assert sorted(merged_report.contract_names) == ["Dashboard", "Login"]
    assert 'id="name-filter"' in result.html


def test_extract_template_round_trips_with_render_json_blob():
    base_html = _report_html("screenshot_to_code@1.0.0", "trace-1", "claude")
    template = extract_template(base_html)

    rebuilt = render_json_blob(extract_report_json(base_html), template=template)

    assert rebuilt == base_html
